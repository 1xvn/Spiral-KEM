//! Public vectors and compile-time guards for the configured state cleanup.
//!
//! These gates cover the advertised SHA state and buffered-state owners. They
//! do not establish that HMAC/HKDF local output arrays, old copies, registers or
//! every backend temporary are erased. Those limits need source and linked-code
//! review in addition to these functional tests.

use hmac::{
    digest::block_api::{Buffer, CoreProxy},
    Hmac, KeyInit, Mac,
};
use sha2::{Sha256, Sha512};

fn hex_bytes(text: &str) -> Vec<u8> {
    hex::decode(text).expect("public RFC vector must be valid hex")
}

#[test]
fn configured_sha_and_buffer_cleanup_contract() {
    fn requires_zeroize_on_drop<T: zeroize::ZeroizeOnDrop>() {}

    // The marker is feature-gated. Unlike needs_drop, these bounds reject a
    // build whose SHA or block-buffer cleanup feature has been disabled.
    requires_zeroize_on_drop::<Sha256>();
    requires_zeroize_on_drop::<Sha512>();
    requires_zeroize_on_drop::<Buffer<<Hmac<Sha256> as CoreProxy>::Core>>();
    requires_zeroize_on_drop::<Buffer<<Hmac<Sha512> as CoreProxy>::Core>>();

    // Hmac/Hkdf have no public ZeroizeOnDrop marker in these pinned versions.
    // Their SHA core and buffer fields obtain recursive Drop cleanup. These
    // checks only guard against losing that ownership, not the cleanup feature:
    // SHA has an empty Drop even when its zeroize feature is disabled.
    assert!(std::mem::needs_drop::<Hmac<Sha256>>());
    assert!(std::mem::needs_drop::<Hmac<Sha512>>());
    assert!(std::mem::needs_drop::<hkdf::Hkdf<Sha256>>());
    assert!(std::mem::needs_drop::<hkdf::Hkdf<Sha512>>());
}

#[test]
fn rfc4231_hmac_sha256_sha512_short_and_long_keys() {
    // RFC 4231 sections 4.2 and 4.7, cases 1 and 6. Expected values are
    // independent published constants, not values generated by another path
    // through the implementation under test. Case 6 exceeds both block sizes.
    let cases = [
        (
            "case 1",
            vec![0x0b; 20],
            &b"Hi There"[..],
            concat!(
                "b0344c61d8db38535ca8afceaf0bf12b8",
                "81dc200c9833da726e9376c2e32cff7"
            ),
            concat!(
                "87aa7cdea5ef619d4ff0b4241a1d6cb0",
                "2379f4e2ce4ec2787ad0b30545e17cde",
                "daa833b7d6b8a702038b274eaea3f4e4",
                "be9d914eeb61f1702e696c203a126854"
            ),
        ),
        (
            "case 6",
            vec![0xaa; 131],
            &b"Test Using Larger Than Block-Size Key - Hash Key First"[..],
            concat!(
                "60e431591ee0b67f0d8a26aacbf5b77f",
                "8e0bc6213728c5140546040f0ee37f54"
            ),
            concat!(
                "80b24263c7c1a3ebb71493c1dd7be8b4",
                "9b46d1f41b4aeec1121b013783f8f352",
                "6b56d037e05f2598bd0fd2215d6a1e52",
                "95e64f73f63f0aec8b915a985d786598"
            ),
        ),
    ];
    for (name, key, message, expected256, expected512) in cases {
        let mut sha256 = Hmac::<Sha256>::new_from_slice(&key).unwrap();
        sha256.update(message);
        assert_eq!(
            sha256.finalize().into_bytes().as_slice(),
            hex_bytes(expected256).as_slice(),
            "RFC 4231 {name} HMAC-SHA-256"
        );

        let mut sha512 = Hmac::<Sha512>::new_from_slice(&key).unwrap();
        sha512.update(message);
        assert_eq!(
            sha512.finalize().into_bytes().as_slice(),
            hex_bytes(expected512).as_slice(),
            "RFC 4231 {name} HMAC-SHA-512"
        );
    }
}

#[test]
fn rfc5869_sha256_extract_and_expand_with_and_without_salt() {
    // RFC 5869 appendix A.1 and A.3. The 42-byte output spans two HKDF blocks,
    // exercising the previous-block path without using production secrets.
    let ikm = [0x0b; 22];
    let salt = hex_bytes("000102030405060708090a0b0c");
    let info = hex_bytes("f0f1f2f3f4f5f6f7f8f9");
    let cases = [
        (
            "case 1",
            Some(salt.as_slice()),
            info.as_slice(),
            concat!(
                "077709362c2e32df0ddc3f0dc47bba63",
                "90b6c73bb50f9c3122ec844ad7c2b3e5"
            ),
            concat!(
                "3cb25f25faacd57a90434f64d0362f2a",
                "2d2d0a90cf1a5a4c5db02d56ecc4c5bf",
                "34007208d5b887185865"
            ),
        ),
        (
            "case 3",
            None,
            &[][..],
            concat!(
                "19ef24a32c717b167f33a91d6f648bdf",
                "96596776afdb6377ac434c1c293ccb04"
            ),
            concat!(
                "8da4e775a563c18f715f802a063c5a31",
                "b8a11f5c5ee1879ec3454e5f3c738d2d",
                "9d201395faa4b61a96c8"
            ),
        ),
    ];
    for (name, salt, info, expected_prk, expected_okm) in cases {
        let (prk, hkdf) = hkdf::Hkdf::<Sha256>::extract(salt, &ikm);
        assert_eq!(
            prk.as_slice(),
            hex_bytes(expected_prk).as_slice(),
            "RFC 5869 {name} PRK"
        );
        let mut okm = [0; 42];
        hkdf.expand(info, &mut okm).unwrap();
        assert_eq!(
            okm.as_slice(),
            hex_bytes(expected_okm).as_slice(),
            "RFC 5869 {name} OKM"
        );
        let from_prk = hkdf::Hkdf::<Sha256>::from_prk(&hex_bytes(expected_prk)).unwrap();
        let mut reconstructed = [0; 42];
        from_prk.expand(info, &mut reconstructed).unwrap();
        assert_eq!(reconstructed, okm, "RFC 5869 {name} from_prk");
    }
}
