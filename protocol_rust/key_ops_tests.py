import hmac
import json
import os
import platform
from pathlib import Path
import select
import stat
import subprocess
import sys
import tempfile
import time
import unittest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from protocol_rust import interop

BINARY = ROOT / "protocol_rust/target/debug/spiral-lab"
WATCHDOG_SECONDS = 5
MAX_STARTUP_REPORT_BYTES = 64 * 1024


def source_hashes():
    # Public build inputs only: never walk generated credential directories.
    from protocol_rust.fuzzing.campaign import source_names
    names = {name for name in source_names() if "target" not in Path(name).parts}
    names.add("protocol_rust/key_ops_tests.py")
    return {name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest()
            for name in sorted(names)}


class KeyOperations(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="spiral-key-ops-")
        self.addCleanup(self.temporary.cleanup)
        self.folder = Path(self.temporary.name)
        os.chmod(self.folder, 0o700)
        self.secrets = []
        self.server_stdout_pending = {}

    def track_secret(self, raw):
        if raw:
            self.secrets.extend((raw, raw.hex().encode("ascii"), base64.b64encode(raw)))

    def audit_output(self, stdout, stderr):
        for output in (stdout, stderr):
            self.assertFalse(b"PRIVATE KEY" in output, "private PEM appeared in output")
            for secret in self.secrets:
                self.assertFalse(secret in output, "private key material appeared in output")

    def invoke(self, arguments, *, umask=-1):
        try:
            completed = subprocess.run(
                [str(BINARY), *map(str, arguments)], cwd=ROOT,
                stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                timeout=WATCHDOG_SECONDS, umask=umask,
            )
        except subprocess.TimeoutExpired as error:
            self.audit_output(error.stdout or b"", error.stderr or b"")
            self.fail("key operation exceeded the subprocess watchdog")
        self.audit_output(completed.stdout, completed.stderr)
        return completed

    def decode_report(self, output):
        try:
            rows = output.splitlines()
            if len(rows) != 1:
                raise ValueError("expected one report")
            report = json.loads(rows[0])
            if not isinstance(report, dict):
                raise ValueError("expected a report object")
            return report
        except (ValueError, UnicodeError):
            self.fail("command did not produce one valid JSON report")

    def private_seed(self, path, raw=None):
        raw = os.urandom(32) if raw is None else raw
        descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(descriptor, "wb") as stream:
            os.fchmod(stream.fileno(), 0o600)
            stream.write(raw)
        self.track_secret(raw)
        return raw

    def assert_private_file(self, path):
        metadata = path.lstat()
        self.assertTrue(stat.S_ISREG(metadata.st_mode), "key is not a regular file")
        self.assertEqual(stat.S_IMODE(metadata.st_mode), 0o600)
        self.assertEqual(metadata.st_uid, os.geteuid())
        self.assertEqual(metadata.st_nlink, 1)
        self.assertEqual(metadata.st_size, 32)

    def check_public_report(self, completed, status, path):
        # Track the newly generated bytes before examining success/failure output.
        raw = path.read_bytes()
        self.track_secret(raw)
        self.audit_output(completed.stdout, completed.stderr)
        self.assertEqual(completed.returncode, 0, "key command failed")
        self.assertFalse(completed.stderr, "successful key command wrote stderr")
        report = self.decode_report(completed.stdout)
        public = Ed25519PrivateKey.from_private_bytes(raw).public_key().public_bytes_raw()
        self.assertEqual(set(report), {"status", "public_key_hex", "public_key_sha256"})
        self.assertEqual(report["status"], status)
        self.assertEqual(report["public_key_hex"], public.hex())
        self.assertEqual(report["public_key_sha256"], hashlib.sha256(public).hexdigest())
        return report

    def generate(self, path, *, umask=-1):
        completed = self.invoke(["auth-keygen", "--auth", path], umask=umask)
        self.assertTrue(path.is_file(), "keygen did not create its destination")
        self.assert_private_file(path)
        return self.check_public_report(completed, "created", path)

    def assert_rejected(self, completed):
        self.assertNotEqual(completed.returncode, 0, "unsafe key input was accepted")
        self.assertFalse(b'"kem"' in completed.stdout,
                         "key CLI entered the KEM execution path")
        self.assertFalse(b'"listening"' in completed.stdout,
                         "key rejection unexpectedly opened a listener")

    def test_keygen_and_public_round_trip_accept_read_only_private_key(self):
        path = self.folder / "auth.bin"
        created = self.generate(path)
        loaded = self.check_public_report(
            self.invoke(["auth-public", "--auth", path]), "loaded", path)
        self.assertEqual(created["public_key_hex"], loaded["public_key_hex"])
        restored_directory = self.folder / "local-restored-file"
        restored_directory.mkdir(mode=0o700)
        restored_path = restored_directory / "auth.bin"
        self.private_seed(restored_path, path.read_bytes())
        os.chmod(restored_path, 0o400)
        restored = self.check_public_report(
            self.invoke(["auth-public", "--auth", restored_path]), "loaded", restored_path)
        self.assertEqual(restored, loaded, "local restored file has different public metadata")
        self.assertEqual(stat.S_IMODE(restored_directory.stat().st_mode), 0o700)
        self.assertEqual(stat.S_IMODE(restored_path.stat().st_mode), 0o400)
        os.chmod(path, 0o400)
        os.chmod(self.folder, 0o500)
        self.addCleanup(os.chmod, self.folder, 0o700)
        self.check_public_report(self.invoke(["auth-public", "--auth", path]), "loaded", path)
        self.assertEqual(stat.S_IMODE(path.stat().st_mode), 0o400,
                         "loading changed key permissions")
        self.assertEqual(stat.S_IMODE(self.folder.stat().st_mode), 0o500,
                         "loading changed directory permissions")

    def test_keygen_sets_exact_mode_independently_of_umask(self):
        public_keys = []
        for mask in (0o000, 0o777):
            with self.subTest(umask=oct(mask)):
                path = self.folder / ("auth-" + oct(mask) + ".bin")
                public_keys.append(self.generate(path, umask=mask)["public_key_hex"])
                self.assertEqual(stat.S_IMODE(self.folder.stat().st_mode), 0o700)
        self.assertEqual(len(set(public_keys)), 2, "keygen reused an authentication key")

    def test_keygen_never_replaces_existing_files_or_special_entries(self):
        target = self.folder / "existing.bin"
        original = self.private_seed(target)
        directory = self.folder / "directory.bin"
        directory.mkdir(mode=0o700)
        link = self.folder / "symlink.bin"
        link.symlink_to(target)
        dangling = self.folder / "dangling.bin"
        dangling.symlink_to(self.folder / "missing.bin")
        fifo = self.folder / "fifo.bin"
        os.mkfifo(fifo, 0o600)
        for path in (target, directory, link, dangling, fifo):
            with self.subTest(entry=path.name):
                metadata = path.lstat()
                self.assert_rejected(self.invoke(["auth-keygen", "--auth", path]))
                after = path.lstat()
                self.assertEqual((after.st_ino, after.st_mode),
                                 (metadata.st_ino, metadata.st_mode),
                                 "rejected keygen changed its destination")
                self.assertTrue(hmac.compare_digest(target.read_bytes(), original),
                                "rejected keygen changed an existing secret")
        self.assertFalse((self.folder / "missing.bin").exists(),
                         "keygen followed a dangling destination symlink")

    def test_concurrent_keygen_has_one_winner_without_replacing_its_key(self):
        path = self.folder / "raced-auth.bin"
        children = [subprocess.Popen(
            [str(BINARY), "auth-keygen", "--auth", str(path)], cwd=ROOT,
            stdout=subprocess.PIPE, stderr=subprocess.PIPE) for _ in range(2)]
        for child in children:
            self.addCleanup(self.stop_server, child)
        results = []
        for child in children:
            try:
                stdout, stderr = child.communicate(timeout=WATCHDOG_SECONDS)
            except subprocess.TimeoutExpired as error:
                self.audit_output(error.stdout or b"", error.stderr or b"")
                self.fail("concurrent keygen exceeded the subprocess watchdog")
            results.append(subprocess.CompletedProcess(child.args, child.returncode, stdout, stderr))
        self.assert_private_file(path)
        self.track_secret(path.read_bytes())
        for completed in results:
            self.audit_output(completed.stdout, completed.stderr)
        self.assertEqual(sum(completed.returncode == 0 for completed in results), 1,
                         "concurrent keygen did not have exactly one winner")
        for completed in results:
            if completed.returncode == 0:
                self.check_public_report(completed, "created", path)
            else:
                self.assert_rejected(completed)

    def test_auth_commands_reject_extra_or_duplicate_options(self):
        source = self.folder / "source.bin"
        self.private_seed(source)
        for mode in ("auth-keygen", "auth-public"):
            for extras in (("--workers", "1"), ("--auth", str(source))):
                with self.subTest(mode=mode, option=extras[0]):
                    path = self.folder / "new.bin" if mode == "auth-keygen" else source
                    self.assert_rejected(self.invoke([mode, "--auth", path, *extras]))
                    self.assertFalse((self.folder / "new.bin").exists(),
                                     "invalid arguments created a key")

    def test_public_rejects_short_and_oversized_seed_files(self):
        for length in (0, 31, 33, 1024 * 1024):
            with self.subTest(length=length):
                path = self.folder / ("seed-" + str(length) + ".bin")
                # Synthetic malformed input, never stored in the result document.
                raw = (b"invalid-seed-fixture-" * ((length // 21) + 1))[:length]
                self.private_seed(path, raw)
                self.assert_rejected(self.invoke(["auth-public", "--auth", path]))
                self.assertEqual(path.stat().st_size, length)

    def test_public_rejects_bad_modes_and_preserves_permissions(self):
        path = self.folder / "auth.bin"
        self.private_seed(path)
        for mode in (0o644, 0o660, 0o200, 0o700):
            with self.subTest(mode=oct(mode)):
                os.chmod(path, mode)
                self.assert_rejected(self.invoke(["auth-public", "--auth", path]))
                self.assertEqual(stat.S_IMODE(path.stat().st_mode), mode,
                                 "loader repaired an insecure file mode")

    def test_public_rejects_symlinks_hardlinks_directories_and_fifo_promptly(self):
        target = self.folder / "auth.bin"
        self.private_seed(target)
        link = self.folder / "link.bin"
        link.symlink_to(target)
        directory = self.folder / "directory.bin"
        directory.mkdir(mode=0o700)
        fifo = self.folder / "fifo.bin"
        os.mkfifo(fifo, 0o600)
        for path in (link, directory, fifo):
            with self.subTest(entry=path.name):
                self.assert_rejected(self.invoke(["auth-public", "--auth", path]))
        hardlink = self.folder / "hardlink.bin"
        os.link(target, hardlink)
        for path in (target, hardlink):
            with self.subTest(entry=path.name, kind="hardlink"):
                self.assert_rejected(self.invoke(["auth-public", "--auth", path]))

    def test_auth_commands_reject_unsafe_parent_and_ancestor_paths(self):
        actual = self.folder / "actual"
        actual.mkdir(mode=0o700)
        target = actual / "auth.bin"
        self.private_seed(target)
        linked = self.folder / "linked"
        linked.symlink_to(actual, target_is_directory=True)
        ancestor = self.folder / "ancestor"
        ancestor.mkdir(mode=0o700)
        nested = ancestor / "private"
        nested.mkdir(mode=0o700)
        nested_target = nested / "auth.bin"
        self.private_seed(nested_target)
        for mode in ("auth-public", "auth-keygen"):
            leaf = "auth.bin" if mode == "auth-public" else "new.bin"
            with self.subTest(command=mode, parent="symlink"):
                self.assert_rejected(self.invoke([mode, "--auth", linked / leaf]))
            permissions_to_reject = (0o755, 0o770, 0o500) if mode == "auth-keygen" else (0o755, 0o770)
            for permissions in permissions_to_reject:
                with self.subTest(command=mode, parent_mode=oct(permissions)):
                    os.chmod(actual, permissions)
                    self.assert_rejected(self.invoke([mode, "--auth", actual / leaf]))
                    self.assertEqual(stat.S_IMODE(actual.stat().st_mode), permissions,
                                     "command repaired its parent permissions")
            os.chmod(actual, 0o700)
            with self.subTest(command=mode, ancestor="writable"):
                os.chmod(ancestor, 0o770)
                self.assert_rejected(self.invoke([mode, "--auth", nested / leaf]))
                self.assertEqual(stat.S_IMODE(ancestor.stat().st_mode), 0o770)
            os.chmod(ancestor, 0o700)
        self.assertFalse((actual / "new.bin").exists())
        self.assertFalse((nested / "new.bin").exists())

    def tls_fixture(self):
        signing, pin = interop.identities(self.folder)
        self.track_secret((self.folder / "auth.bin").read_bytes())
        pem = (self.folder / "key.pem").read_bytes()
        self.track_secret(pem)
        tls_key = serialization.load_pem_private_key(pem, password=None)
        self.track_secret(tls_key.private_bytes_raw())
        self.track_secret(tls_key.private_bytes(
            serialization.Encoding.DER, serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption()))
        return signing, pin

    def protocol_args(self, role, **options):
        # Reuse the loopback harness's actual server/client argument contract.
        return interop.Interop.args(self, role, **options)[1:]

    def test_server_rejects_both_secret_file_types_before_listening_or_kem_jobs(self):
        self.tls_fixture()
        for filename in ("auth.bin", "key.pem"):
            path = self.folder / filename
            original = path.read_bytes()
            invalid_contents = {}
            if filename == "key.pem":
                invalid_contents = {
                    "oversized_pem": original + b"\n" * (65537 - len(original)),
                    "duplicate_pem": original + original,
                    "malformed_trailing_pem": original + (
                        b"\n-----BEGIN PRIVATE KEY-----\n!!!\n-----END PRIVATE KEY-----\n"),
                }
            for entry in ("public_mode", "symlink", "fifo", *invalid_contents):
                with self.subTest(secret_file=filename, entry=entry):
                    saved = self.folder / (filename + ".saved")
                    if entry == "public_mode":
                        os.chmod(path, 0o644)
                    elif entry in invalid_contents:
                        path.unlink()
                        self.private_seed(path, invalid_contents[entry])
                    else:
                        path.rename(saved)
                        if entry == "symlink":
                            path.symlink_to(saved)
                        else:
                            os.mkfifo(path, 0o600)
                    try:
                        completed = self.invoke(self.protocol_args(
                            "server", port=0, connections=1, messages=1))
                        self.assertNotEqual(completed.returncode, 0)
                        self.assertFalse(b'"listening"' in completed.stdout,
                                         "server listened before rejecting a secret file")
                        report = self.decode_report(completed.stdout)
                        self.assertEqual(report.get("status"), "failed")
                        self.assertEqual(report.get("kem", {}).get("executed_jobs"), 0)
                        self.assertEqual(report.get("kem", {}).get("live_keys"), 0)
                    finally:
                        if entry == "public_mode":
                            os.chmod(path, 0o600)
                        elif entry in invalid_contents:
                            path.unlink()
                            self.private_seed(path, original)
                        else:
                            path.unlink()
                            saved.rename(path)
                    self.assertTrue(hmac.compare_digest(path.read_bytes(), original),
                                    "server rejection changed private file contents")

    def start_server(self):
        process = subprocess.Popen(
            [str(BINARY), *self.protocol_args("server", port=0, connections=1, messages=1)],
            cwd=ROOT, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        )
        self.addCleanup(self.stop_server, process)
        ready = False
        output = bytearray()
        deadline = time.monotonic() + WATCHDOG_SECONDS
        try:
            while b"\n" not in output:
                remaining = deadline - time.monotonic()
                if remaining <= 0:
                    self.fail("TLS server startup exceeded the watchdog")
                if len(output) >= MAX_STARTUP_REPORT_BYTES:
                    self.fail("TLS server startup report exceeded its size bound")
                readable, _, _ = select.select([process.stdout], [], [], remaining)
                if not readable:
                    self.fail("TLS server startup exceeded the watchdog")
                chunk = os.read(process.stdout.fileno(), min(
                    4096, MAX_STARTUP_REPORT_BYTES - len(output)))
                if not chunk:
                    self.fail("TLS server exited before completing its startup report")
                output.extend(chunk)
            self.audit_output(bytes(output), b"")
            line, _separator, pending = output.partition(b"\n")
            report = self.decode_report(bytes(line))
            self.assertTrue(report.get("loopback_only"), "server was not loopback-only")
            port = report.get("listening")
            self.assertTrue(type(port) is int and 1 <= port <= 65535,
                            "server did not report a valid loopback port")
            self.server_stdout_pending[process] = bytes(pending)
            ready = True
            return process, port
        except OSError:
            self.fail("TLS server startup I/O failed")
        finally:
            if not ready:
                stdout, stderr = self.stop_server(process)
                self.audit_output(bytes(output) + stdout, stderr)

    @staticmethod
    def stop_server(process):
        if process.poll() is None:
            process.kill()
        return process.communicate(timeout=WATCHDOG_SECONDS)

    def finish_server(self, process):
        try:
            stdout, stderr = process.communicate(timeout=WATCHDOG_SECONDS)
        except subprocess.TimeoutExpired as error:
            self.audit_output(error.stdout or b"", error.stderr or b"")
            self.fail("TLS server completion exceeded the watchdog")
        stdout = self.server_stdout_pending.pop(process, b"") + stdout
        self.audit_output(stdout, stderr)
        return self.decode_report(stdout)

    def test_rotation_rejects_old_pin_and_new_pin_authenticates_echo_and_close(self):
        _fixture_signing, pin = self.tls_fixture()
        old_path = self.folder / "old-auth.bin"
        old_public = self.generate(old_path)
        active = self.folder / "auth.bin"
        active.unlink()
        new_public = self.generate(active)
        self.assertNotEqual(old_public["public_key_hex"], new_public["public_key_hex"])
        pin_path = self.folder / "pin.json"

        for public, accepted in ((old_public, False), (new_public, True)):
            with self.subTest(pin="new" if accepted else "old"):
                pin_path.write_text(json.dumps(pin | {"public_key_hex": public["public_key_hex"]}))
                server, port = self.start_server()
                client = self.invoke(self.protocol_args(
                    "client", port=port, connections=1, messages=1, payload=64, pipeline=1))
                client_report = self.decode_report(client.stdout)
                server_report = self.finish_server(server)
                for report in (client_report, server_report):
                    self.assertEqual(report.get("kem", {}).get("live_keys"), 0)
                if not accepted:
                    self.assertNotEqual(client.returncode, 0, "rotated-out pin was accepted")
                    self.assertNotEqual(server.returncode, 0)
                    self.assertEqual(client_report.get("status"), "failed")
                    self.assertEqual(server_report.get("status"), "failed")
                    self.assertEqual(client_report["kem"]["executed_jobs"], 0,
                                     "old pin was rejected after client encapsulation")
                    self.assertEqual(server_report["kem"]["executed_jobs"], 1)
                    continue
                self.assertEqual(client.returncode, 0, "new pin failed authentication")
                self.assertEqual(server.returncode, 0)
                self.assertFalse(client.stderr, "successful client wrote stderr")
                self.assertEqual(client_report.get("status"), "passed")
                self.assertEqual(server_report.get("status"), "passed")
                self.assertTrue(server_report.get("auth_key_closed"))
                self.assertTrue(server_report.get("admission_released"))
                for report in (client_report, server_report):
                    self.assertEqual(len(report.get("sessions", [])), 1)
                    self.assertTrue(report["sessions"][0].get("authenticated_close"))
                    self.assertEqual(report["sessions"][0].get("messages"), 1)
                for field in ("session_id", "binding_hash", "transcript_hash"):
                    self.assertEqual(client_report["sessions"][0].get(field),
                                     server_report["sessions"][0].get(field))


def main():
    global BINARY
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, default=BINARY)
    parser.add_argument("--json", type=Path)
    arguments = parser.parse_args()
    if not sys.platform.startswith("linux"):
        parser.error("key operations integration tests require Linux")
    BINARY = arguments.binary.expanduser().resolve()
    if not BINARY.is_file():
        parser.error("build spiral-lab before running key operations integration tests")
    before = source_hashes()
    binary_hash = hashlib.sha256(BINARY.read_bytes()).hexdigest()
    interop.BINARY = BINARY
    result = unittest.TextTestRunner(verbosity=2).run(
        unittest.defaultTestLoader.loadTestsFromTestCase(KeyOperations))
    unchanged = (before == source_hashes()
                 and binary_hash == hashlib.sha256(BINARY.read_bytes()).hexdigest())
    passed = result.wasSuccessful() and result.testsRun > 0 and not result.skipped and unchanged
    summary = {
        "schema": "spiral-rust-key-operations/v1",
        "status": "passed" if passed else "failed",
        "tests": result.testsRun,
        "failures": len(result.failures),
        "errors": len(result.errors),
        "skipped": len(result.skipped),
        "platform": dict(platform.uname()._asdict(), node="redacted"),
        "effective_uid": os.geteuid(),
        "binary_sha256": binary_hash,
        "runner_sha256": before["protocol_rust/key_ops_tests.py"],
        "source_sha256": before,
        "source_and_binary_unchanged": unchanged,
        "failed_tests": [test.id() for test, _traceback in result.failures],
        "error_tests": [test.id() for test, _traceback in result.errors],
        "scope": "Linux key-file policy, public-only CLI output, local restored-file agreement, and loopback TLS key rotation",
    }
    if arguments.json:
        arguments.json.write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary), flush=True)
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
